<?php
// Printable payment receipt (v35). Only the participant who made the payment can open it.
Auth::requireRole('participant');
$db = Database::connection();

$stmt = $db->prepare(
    'SELECT pay.*, COALESCE(pay.paid_at, pay.reviewed_at, pay.submitted_at) AS pay_date, r.id AS reg_id, e.name AS event_name, e.event_date, e.venue, o.organization_name, u.full_name, u.email
     FROM payments pay
     JOIN registrations r ON r.id = pay.registration_id
     JOIN participants p ON p.id = r.participant_id
     JOIN users u ON u.id = p.user_id
     JOIN events e ON e.id = r.event_id
     JOIN organizers o ON o.id = e.organizer_id
     WHERE pay.id = :id AND p.user_id = :uid AND pay.status IN ("approved", "refunded")'
);
$stmt->execute(['id' => (int) ($_GET['id'] ?? 0), 'uid' => Auth::id()]);
$pay = $stmt->fetch();
if (!$pay) {
    flash('error', 'Receipt not found.');
    redirect('my-payments');
}
$settings = $db->query('SELECT system_name FROM system_settings LIMIT 1')->fetch() ?: ['system_name' => 'EVORA'];
$paidTo = match ($pay['payment_channel']) {
    'paypal' => $pay['organization_name'] . ' (paid directly through PayPal)',
    'cash_walkin' => $pay['organization_name'] . ' (cash, walk-in)',
    'paymongo' => 'EVORA (collected through PayMongo)',
    default => $pay['organization_name'],
};
?>
<!doctype html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Receipt <?= e($pay['reference_no'] ?: ('#' . $pay['id'])) ?> — EVORA</title>
    <link href="https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css" rel="stylesheet">
    <link href="https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/bootstrap-icons.css" rel="stylesheet">
    <link href="<?= assetUrl('css/theme.css') ?>" rel="stylesheet">
    <?= themeInit() ?>
    <?= pageHead($pageMeta ?? []) ?>
    <style>
        body { background: var(--evora-bg); }
        .receipt { max-width: 640px; margin: 32px auto; background: var(--evora-surface); border-radius: 12px; padding: 32px; }
        .receipt dt { font-weight: 500; color: var(--evora-text-muted); }
        @media print { body { background: #fff; } .receipt { margin: 0; box-shadow: none; } .no-print { display: none !important; } }
    </style>
</head>
<body>
<div class="receipt shadow-sm">
    <div class="d-flex justify-content-between align-items-start mb-4">
        <div>
            <h1 class="h4 fw-bold mb-0"><?= e($settings['system_name'] ?: 'EVORA') ?></h1>
            <div class="small text-muted">Payment Receipt</div>
        </div>
        <span class="badge <?= $pay['status'] === 'refunded' ? 'bg-info' : 'bg-success' ?> fs-6"><?= $pay['status'] === 'refunded' ? 'REFUNDED' : 'PAID' ?></span>
    </div>
    <dl class="row small mb-4">
        <dt class="col-5">Reference no.</dt><dd class="col-7"><?= e($pay['reference_no'] ?: ('#' . $pay['id'])) ?></dd>
        <dt class="col-5">Date paid</dt><dd class="col-7"><?= $pay['pay_date'] ? date('F d, Y g:i A', strtotime($pay['pay_date'])) : '—' ?></dd>
        <dt class="col-5">Paid by</dt><dd class="col-7"><?= e($pay['full_name']) ?></dd>
        <dt class="col-5">Paid to</dt><dd class="col-7"><?= e($paidTo) ?></dd>
        <dt class="col-5">Payment method</dt><dd class="col-7"><?= e(paymentChannelLabel($pay['payment_channel'])) ?></dd>
        <?php if ($pay['gateway_payment_id']): ?><dt class="col-5">Transaction ID</dt><dd class="col-7 text-break"><?= e($pay['gateway_payment_id']) ?></dd><?php endif; ?>
        <dt class="col-5">Event</dt><dd class="col-7"><?= e($pay['event_name']) ?><?= $pay['event_date'] ? '<br><span class="text-muted">' . date('F d, Y', strtotime($pay['event_date'])) . ($pay['venue'] ? ' · ' . e($pay['venue']) : '') . '</span>' : '' ?></dd>
        <dt class="col-5">Registration</dt><dd class="col-7">#<?= (int) $pay['reg_id'] ?></dd>
    </dl>
    <div class="d-flex justify-content-between border-top pt-3 mb-4">
        <span class="fw-semibold">Amount</span><span class="h5 fw-bold mb-0"><?= currency($pay['amount']) ?></span>
    </div>
    <p class="small text-muted mb-4">This receipt was generated by EVORA from its payment records.<?= $pay['payment_channel'] === 'paypal' ? ' The money was paid directly to the organizer through PayPal; EVORA did not receive or hold it.' : '' ?></p>
    <div class="d-flex gap-2 no-print">
        <button type="button" class="btn btn-evora-primary" onclick="window.print()">Print / Save as PDF</button>
        <a class="btn btn-outline-secondary" href="<?= url('my-payments') ?>">Back to Payments &amp; Receipts</a>
    </div>
</div>
</body>
</html>
