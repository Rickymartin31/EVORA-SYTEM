<?php
Auth::requireRole('admin');
$db = Database::connection();

$page = max(1, (int) ($_GET['page'] ?? 1));
$perPage = 25;
$offset = ($page - 1) * $perPage;

$total = (int) $db->query('SELECT COUNT(*) c FROM reports')->fetch()['c'];

// related_id is polymorphic (event id when scope='event', otherwise unused),
// so this is a conditional LEFT JOIN, not a real foreign key — same reasoning
// documented on reports.related_id in schema.sql.
$stmt = $db->prepare(
    "SELECT rp.report_type, rp.scope, rp.related_id, rp.generated_at,
        u.full_name AS generated_by_name, ro.name AS generated_by_role,
        e.name AS event_name
     FROM reports rp
     JOIN users u ON u.id = rp.generated_by
     JOIN roles ro ON ro.id = u.role_id
     LEFT JOIN events e ON rp.scope = 'event' AND e.id = rp.related_id
     ORDER BY rp.generated_at DESC
     LIMIT :limit OFFSET :offset"
);
$stmt->bindValue(':limit', $perPage, PDO::PARAM_INT);
$stmt->bindValue(':offset', $offset, PDO::PARAM_INT);
$stmt->execute();
$history = $stmt->fetchAll();

$totalPages = (int) ceil($total / $perPage);

$reportTypeLabels = [
    'platform_statistics' => 'Platform Statistics',
    'organizer_statistics' => 'Organizer Statistics',
    'event_statistics' => 'Event Statistics',
    'payment_summary' => 'Payment Summary',
    'event_summary' => 'Event Summary',
    'participant_list' => 'Participant List',
    'payment_summary' => 'Payment Summary',
    'attendance_report' => 'Attendance Report',
    'staff_activity' => 'Staff Activity',
    'completion_report' => 'Completion Report',
];

$pageDescription = 'Reports that were generated earlier.';
$pageTitle = 'Report History';
$activeRoute = 'admin-report-history';
include EVORA_ROOT . '/modules/shared/partials/layout_top.php';
?>
<div class="card-evora p-4">
    <h6 class="fw-semibold mb-3">Report History <span class="text-muted small">(<?= $total ?> total)</span></h6>
    <div class="table-responsive">
        <table class="table align-middle table-sm">
            <thead><tr><th>Report Type</th><th>Generated By</th><th>User Role</th><th>Scope / Event</th><th>Date Generated</th><th>Time Generated</th></tr></thead>
            <tbody>
            <?php if (empty($history)): ?>
                <tr><td colspan="6"><?= emptyState('bi-archive', 'No reports have been generated yet.') ?></td></tr>
            <?php endif; ?>
            <?php foreach ($history as $h): ?>
                <tr>
                    <td><?= e($reportTypeLabels[$h['report_type']] ?? $h['report_type']) ?></td>
                    <td><?= e($h['generated_by_name']) ?></td>
                    <td><span class="badge bg-light text-dark border"><?= ucfirst(e($h['generated_by_role'])) ?></span></td>
                    <td class="small">
                        <?php if ($h['scope'] === 'event' && $h['event_name']): ?>
                            <?= e($h['event_name']) ?>
                        <?php elseif ($h['scope'] === 'event'): ?>
                            Event #<?= (int) $h['related_id'] ?> <span class="text-muted">(deleted)</span>
                        <?php else: ?>
                            <?= ucfirst(e($h['scope'])) ?>-wide
                        <?php endif; ?>
                    </td>
                    <td class="small"><?= date('M d, Y', strtotime($h['generated_at'])) ?></td>
                    <td class="small text-muted"><?= date('h:i:s A', strtotime($h['generated_at'])) ?></td>
                </tr>
            <?php endforeach; ?>
            </tbody>
        </table>
    </div>
    <?php if ($totalPages > 1): ?>
    <nav>
        <ul class="pagination pagination-sm mb-0">
            <?php for ($i = 1; $i <= $totalPages; $i++): ?>
                <li class="page-item <?= $i === $page ? 'active' : '' ?>"><a class="page-link" href="<?= url('admin-report-history', ['page' => $i]) ?>"><?= $i ?></a></li>
            <?php endfor; ?>
        </ul>
    </nav>
    <?php endif; ?>
</div>
<?php include EVORA_ROOT . '/modules/shared/partials/layout_bottom.php'; ?>
